#!/usr/bin/env python3
"""Generate the per-namespace read RoleBindings for the Authentik group `root-agents` (derio-net/frank#912).

Namespaces = the in-cluster destination namespaces of the Frank root chart's apps (keys `frank/*`,
via life_sessions._destinations(), which also yields `hop/*` keys that do not exist on Frank), minus
PROTECTED and EXCLUDED. RBAC cannot exclude namespaces from a ClusterRoleBinding, hence one RoleBinding each.

  apps/authentik-extras/manifests/root-agents-rbac.yaml

Usage: scripts/root_agents_rbac.py [--write | --check]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

import life_sessions  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "apps/authentik-extras/manifests/root-agents-rbac.yaml"
PROTECTED = frozenset({"upgrade-sessions", "cluster-update-fr", "runs-fr"})
# Credential-store namespaces: pod specs, pod logs and ConfigMaps there can carry credentials (literal env,
# tokens in logs), so root-agents gets no read at all, not only no Secrets (operator decision 2026-11-14).
EXCLUDED = frozenset({"authentik", "infisical", "argocd", "kube-system", "longhorn-system"})
HEADER = ("# GENERATED by scripts/root_agents_rbac.py --write from the Frank root chart's app destinations.\n"
          "# Do not edit by hand. A new app namespace is denied to root-agents until this is regenerated.\n"
          "# Never bound: upgrade-sessions, cluster-update-fr, runs-fr, authentik, infisical, argocd, kube-system,\n"
          "# longhorn-system (derio-net/frank#912).\n")


def namespaces() -> list[str]:
    dest = life_sessions._destinations()
    return sorted({ns for k, ns in dest.items() if k.startswith("frank/")} - PROTECTED - EXCLUDED)


def docs() -> list[dict]:
    return [{"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "RoleBinding",
             "metadata": {"name": "root-agents-ns-read", "namespace": ns},
             "subjects": [{"kind": "Group", "name": "root-agents", "apiGroup": "rbac.authorization.k8s.io"}],
             "roleRef": {"kind": "ClusterRole", "name": "root-agents-ns-read",
                         "apiGroup": "rbac.authorization.k8s.io"}} for ns in namespaces()]


def render() -> str:
    return HEADER + "".join("---\n" + yaml.safe_dump(d, sort_keys=False) for d in docs())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    want = render()
    if a.write:
        OUT.write_text(want)
        return 0
    if not OUT.exists() or OUT.read_text() != want:
        print("stale: root-agents-rbac.yaml -- run scripts/root_agents_rbac.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
