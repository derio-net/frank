#!/usr/bin/env python3
"""Generate the upgrade-session network policies and per-app Roles (plan 2026-10-31--life--update-security-lifecycle, phase 5).

One table (ENDPOINTS) says what each upgrade type may reach; the policy facts
(scripts/tests/fixtures/life/app-facts.yaml) say which Frank apps are stateful or run Argo
Rollouts. From those two this writes:

  apps/upgrade-sessions/manifests/networkpolicies.yaml   default-deny + one egress policy per type
  apps/upgrade-sessions/manifests/app-roles.yaml         static Roles in each stateful / Rollouts
                                                          app namespace, bound to the session SAs

Usage: scripts/life_sessions.py [--write | --check]
"""
from __future__ import annotations

import argparse
import functools
import re
import sys
from urllib.parse import urlsplit
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

import life_policy  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MAN = ROOT / "apps/upgrade-sessions/manifests"
NS = "upgrade-sessions"
TYPES = ("chart-major", "stateful", "rollouts", "frank-os", "hop-os")
TYPE_LABEL = "cluster-update.fr/type"
SEARCH = (f"{NS}.svc.cluster.local", "svc.cluster.local", "cluster.local")  # pod resolv.conf, ndots:5

GITHUB = ("api.github.com", "github.com")  # API commits + git fetch of frank; no gist/raw/uploads
MODELS = ("api.anthropic.com", "console.anthropic.com", "claude.ai", "platform.claude.com",
          "api.openai.com", "auth.openai.com", "chatgpt.com")
OMNI = "omni.frank.derio.net"
FRANK_NODES = ("192.168.55.21", "192.168.55.22", "192.168.55.23", "192.168.55.31",
               "192.168.55.71", "192.168.55.41", "192.168.55.42")
HEADSCALE = "headscale.hop.derio.net"
DERP = "derp*.tailscale.com"  # headscale's derp.urls is Tailscale's default map plus its own region

# Every type: GitHub, model providers, the kube API, the console's session API, Gitea (CI logs).
COMMON_FQDNS = [(GITHUB + MODELS, [("443", "TCP")])]
ENDPOINTS = {
    "chart-major": {"fqdns": COMMON_FQDNS},
    "stateful": {"fqdns": COMMON_FQDNS},
    "rollouts": {"fqdns": COMMON_FQDNS},
    "frank-os": {"fqdns": COMMON_FQDNS + [((OMNI,), [("443", "TCP")])],
                 "cidrs": (FRANK_NODES, [("50000", "TCP")])},
    "hop-os": {"fqdns": COMMON_FQDNS + [((HEADSCALE,), [("443", "TCP"), ("3478", "UDP")]),
                                        ((DERP,), [("443", "TCP"), ("3478", "UDP")])]},
}
HEADER = ("# GENERATED by scripts/life_sessions.py --write from its ENDPOINTS and VERIFIES tables,\n"
          "# smoke/*/*.yaml, scripts/tests/fixtures/life/app-facts.yaml and session-target-ports.yaml.\n"
          "# Do not edit by hand.\n")


@functools.lru_cache(maxsize=None)
def _destinations() -> dict[str, str]:
    return {a["key"]: a["app"]["spec"]["destination"].get("namespace", "default")
            for a in life_policy.applications()}


def app_namespaces(flag: str) -> list[str]:
    """Namespaces of the Frank apps whose fact `flag` (stateful | rollout) is true.

    Frank only: a session pod runs on Frank, and Hop's stateful apps sit on static Hetzner PVs
    with no Longhorn to snapshot. A Role here is inert on an app's own Services.
    """
    facts = life_policy.load_facts()
    dest = _destinations()
    return sorted({dest[k] for k, f in facts.items() if f[flag] and k.startswith("frank/") and k in dest})


# THE never-list (p5-sec-1). A session never reaches these over the network, whatever a smoke
# file names: secret stores and identity (infisical, authentik), agent pods holding other
# credentials (secure-agent-pod, hermes-agent-shell, agents), unauthenticated admin APIs
# (Longhorn manager deletes volumes; VictoriaMetrics/Logs serve delete endpoints), the
# unauthenticated retrieval server (no auth story, see test_ovms_retrieval_manifests), the control
# plane, and the session machinery itself. Never a database, cache or SSH port either.
NEVER_NAMESPACES = frozenset({"infisical", "authentik", "secure-agent-pod", "hermes-agent-shell", "agents",
                              "cluster-update-fr", "kube-system", "longhorn-system", "monitoring", "retrieval", NS})
NEVER_PORTS = frozenset({22, 3306, 5432, 6379, 27017})

# Which apps' smoke checks each type runs to verify (R16). stateful / rollouts: every Frank app
# with that fact (no per-app pod label exists yet, so one policy covers the type). OS steps:
# the apps their brief names; Hop's in-cluster Services are not routable from Frank, so hop-os
# keeps only the public hosts.
VERIFIES = {
    "chart-major": ("frank", ()),
    "stateful": ("frank", "stateful"),
    "rollouts": ("frank", "rollout"),
    "frank-os": ("frank", ("argocd", "cilium", "longhorn", "traefik")),
    "hop-os": ("hop", ("caddy", "headscale", "blog")),
}
TARGET_PORTS_FILE = ROOT / "scripts/tests/fixtures/life/session-target-ports.yaml"
SVC_HOST = re.compile(r"^([\w-]+)\.([\w-]+)\.svc\.cluster\.local$")


def _verified_apps(typ: str) -> tuple[str, list[str]]:
    cluster, apps = VERIFIES[typ]
    if isinstance(apps, str):
        facts = life_policy.load_facts()
        apps = sorted(k.split("/", 1)[1] for k, f in facts.items() if f[apps] and k.startswith(cluster + "/"))
    return cluster, list(apps)


def _parse_target(target: str) -> tuple[str, int] | None:
    t = target.split()[-1]  # "POST http://..." -> the URL
    if "://" in t:
        u = urlsplit(t)
        if u.scheme not in ("http", "https"):
            return None
        return u.hostname, u.port or (443 if u.scheme == "https" else 80)
    host, _, port = t.rpartition(":")
    return (host, int(port)) if host and port.isdigit() else None


def smoke_targets(typ: str) -> list[tuple[str, int]]:
    """(host, Service port) of every network smoke check of the apps this type verifies."""
    cluster, apps = _verified_apps(typ)
    out = set()
    for app in apps:
        path = ROOT / "smoke" / cluster / f"{app}.yaml"
        if not path.exists():
            continue
        for c in yaml.safe_load(path.read_text())["checks"]:
            if c["kind"] in ("http", "tcp", "functional"):
                hp = _parse_target(c["target"])
                # another cluster's Services are not routable from a pod on Frank
                if hp and (cluster == "frank" or not SVC_HOST.match(hp[0])):
                    out.add(hp)
    return sorted(out)


def _allowed(host: str, port: int) -> bool:
    m = SVC_HOST.match(host)
    return bool(m) and m.group(2) not in NEVER_NAMESPACES and port not in NEVER_PORTS


def resolve_target_ports() -> dict[str, list[int]]:
    """{"<svc host>:<port>": [pod ports]} for every allowed in-cluster Frank smoke target, from
    the render of the app whose smoke file names it. Cilium matches the pod port after service
    translation, so a rule on the Service port alone would refuse the check. Slow (helm)."""
    import tempfile

    import render_all_images as r

    owners: dict[str, set[tuple[str, int]]] = {}
    for typ in TYPES:
        cluster, apps = _verified_apps(typ)
        if cluster != "frank":
            continue
        for app in apps:
            path = ROOT / "smoke/frank" / f"{app}.yaml"
            if not path.exists():
                continue
            for c in yaml.safe_load(path.read_text())["checks"]:
                hp = _parse_target(c["target"]) if c["kind"] in ("http", "tcp", "functional") else None
                if hp and _allowed(*hp):
                    owners.setdefault(app, set()).add(hp)
    entries = {e["key"]: e["app"] for e in life_policy.applications()}
    out = {}
    for app, targets in sorted(owners.items()):
        spec = entries[f"frank/{app}"]["spec"]
        docs = []
        for src in spec.get("sources") or [spec["source"]]:
            if "ref" in src and "chart" not in src and "path" not in src:
                continue
            with tempfile.TemporaryDirectory() as td:
                docs += [d for d in yaml.safe_load_all(r.render_source(entries[f"frank/{app}"], src, Path(td)))
                         if isinstance(d, dict)]
        named = {}
        for d in docs:
            for c in _containers(d):
                for p in c.get("ports", []) or []:
                    if p.get("name"):
                        named.setdefault(p["name"], set()).add(p["containerPort"])
        for host, port in targets:
            name, ns = SVC_HOST.match(host).groups()
            backends = set()
            for d in docs:
                if d.get("kind") == "Service" and d["metadata"]["name"] == name:
                    for sp in d["spec"].get("ports", []):
                        if sp.get("port") == port:
                            tp = sp.get("targetPort") or port
                            backends |= named.get(tp, set()) if isinstance(tp, str) else {int(tp)}
            out[f"{host}:{port}"] = sorted(backends) or [port]
    return out


def _containers(d: dict) -> list[dict]:
    spec = d.get("spec") or {}
    tmpl = (spec.get("template") or {}).get("spec") or (spec.get("jobTemplate") or {}).get("spec", {}).get("template", {}).get("spec") or spec
    return list(tmpl.get("containers") or []) + list(tmpl.get("initContainers") or [])


def load_target_ports() -> dict[str, list[int]]:
    return yaml.safe_load(TARGET_PORTS_FILE.read_text())["targets"]


def app_targets(typ: str) -> dict[str, list[int]]:
    """{namespace: pod ports} a session of this type may reach: its verified apps' smoke checks,
    minus the never-lists. gitea's HTTP port is already a common rule."""
    resolved = load_target_ports()
    out: dict[str, set[int]] = {}
    for host, port in smoke_targets(typ):
        if not _allowed(host, port):
            continue
        ns = SVC_HOST.match(host).group(2)
        backends = set(resolved[f"{host}:{port}"]) - NEVER_PORTS
        if ns == "gitea":
            backends -= {3000}
        if backends:
            out.setdefault(ns, set()).update(backends)
    return {ns: sorted(p) for ns, p in sorted(out.items())}


def public_targets(typ: str) -> list[str]:
    """Public smoke hosts (https) an OS step verifies from outside: Hop's edge."""
    return sorted({h for h, p in smoke_targets(typ) if not h.endswith(".svc.cluster.local") and p == 443}) \
        if VERIFIES[typ][0] == "hop" else []


def _ports(pairs):
    return [{"ports": [{"port": p, "protocol": proto} for p, proto in pairs]}]


def _ep(**labels):
    return {"matchLabels": dict(labels)}


def _fqdn(name):
    return {"matchPattern": name} if "*" in name else {"matchName": name}


def _dns_names(typ: str) -> list[str]:
    spec = ENDPOINTS[typ]
    names = [n for group, _ in spec["fqdns"] for n in group]
    names += [h for h in public_targets(typ) if h not in names]
    out = []
    for n in names:
        out += [n] + [f"{n}.{s}" for s in SEARCH]
    out += ["gitea-http.gitea.svc.cluster.local",
            "cluster-update-fr-session.cluster-update-fr.svc.cluster.local",
            "kubernetes.default.svc.cluster.local"]
    out += [h for h, p in smoke_targets(typ) if _allowed(h, p)
            and set(load_target_ports()[f"{h}:{p}"]) - NEVER_PORTS]
    return list(dict.fromkeys(out))


def type_policy(typ: str) -> dict:
    spec = ENDPOINTS[typ]
    egress = [{
        "toEndpoints": [_ep(**{"k8s:io.kubernetes.pod.namespace": "kube-system", "k8s-app": "kube-dns"})],
        "toPorts": [{"ports": [{"port": "53", "protocol": "UDP"}, {"port": "53", "protocol": "TCP"}],
                     "rules": {"dns": [_fqdn(n) for n in _dns_names(typ)]}}],
    }]
    for group, pairs in spec["fqdns"]:
        egress.append({"toFQDNs": [_fqdn(n) for n in group], "toPorts": _ports(pairs)})
    egress.append({"toEntities": ["kube-apiserver"], "toPorts": _ports([("6443", "TCP")])})
    egress.append({"toEndpoints": [_ep(**{"k8s:io.kubernetes.pod.namespace": "cluster-update-fr",
                                          "app.kubernetes.io/name": "cluster-update-fr"})],
                   "toPorts": _ports([("8081", "TCP")])})
    egress.append({"toEndpoints": [_ep(**{"k8s:io.kubernetes.pod.namespace": "gitea"})],
                   "toPorts": _ports([("3000", "TCP")])})
    if "cidrs" in spec:
        ips, pairs = spec["cidrs"]
        egress.append({"toCIDR": [f"{ip}/32" for ip in ips], "toPorts": _ports(pairs)})
    # The smoke checks R16 asks the session to run (allowlist, p5-sec-1): one rule per
    # namespace, bound to the pod ports of exactly the Services those checks name.
    for ns, nsports in app_targets(typ).items():
        egress.append({"toEndpoints": [_ep(**{"k8s:io.kubernetes.pod.namespace": ns})],
                       "toPorts": _ports([(str(p), "TCP") for p in nsports])})
    extra = [h for h in public_targets(typ) if h not in [n for g, _ in spec["fqdns"] for n in g]]
    if extra:
        egress.append({"toFQDNs": [_fqdn(h) for h in extra], "toPorts": _ports([("443", "TCP")])})
    return {"apiVersion": "cilium.io/v2", "kind": "CiliumNetworkPolicy",
            "metadata": {"name": f"upgrade-session-{typ}", "namespace": NS},
            "spec": {"endpointSelector": _ep(**{TYPE_LABEL: typ}), "egress": egress}}


def network_policies() -> list[dict]:
    deny = {"apiVersion": "cilium.io/v2", "kind": "CiliumNetworkPolicy",
            "metadata": {"name": "upgrade-sessions-default-deny", "namespace": NS},
            "spec": {"endpointSelector": {}, "ingress": [{}], "egress": [{}],
                     # A deny outranks every allow: no session reaches SSH anywhere (not the Omni
                     # host, not an in-cluster sshd such as secure-agent-pod's).
                     "egressDeny": [{"toEntities": ["all"], "toPorts": _ports([("22", "TCP")])}]}}
    return [deny] + [type_policy(t) for t in TYPES]


def _role(name, ns, rules):
    return {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "Role",
            "metadata": {"name": name, "namespace": ns}, "rules": rules}


def _binding(name, ns, sa):
    return {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "RoleBinding",
            "metadata": {"name": name, "namespace": ns},
            "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "Role", "name": name},
            "subjects": [{"kind": "ServiceAccount", "name": sa, "namespace": NS}]}


def app_roles() -> list[dict]:
    out = []
    sa = "upgrade-session-stateful"
    name = "upgrade-session-stateful-snapshot"
    for ns in app_namespaces("stateful"):
        rules = [{"apiGroups": [""], "resources": ["persistentvolumeclaims"], "verbs": ["get", "list"]},
                 {"apiGroups": ["snapshot.storage.k8s.io"], "resources": ["volumesnapshots"],
                  "verbs": ["create", "get", "list"]}]
        if ns == "longhorn-system":
            rules.append({"apiGroups": ["longhorn.io"], "resources": ["snapshots"], "verbs": ["create", "get", "list"]})
        out += [_role(name, ns, rules), _binding(name, ns, sa)]
    if "longhorn-system" not in app_namespaces("stateful"):
        rules = [{"apiGroups": ["longhorn.io"], "resources": ["snapshots"], "verbs": ["create", "get", "list"]}]
        out += [_role(name, "longhorn-system", rules), _binding(name, "longhorn-system", sa)]
    sa = "upgrade-session-rollouts"
    name = "upgrade-session-rollouts-decide"
    for ns in app_namespaces("rollout"):
        rules = [{"apiGroups": ["argoproj.io"], "resources": ["rollouts"], "verbs": ["get", "list"]},
                 {"apiGroups": ["argoproj.io"], "resources": ["rollouts/status"], "verbs": ["patch"]}]
        out += [_role(name, ns, rules), _binding(name, ns, sa)]
    return out


def render(docs: list[dict]) -> str:
    return HEADER + "---\n".join(yaml.safe_dump(d, sort_keys=False, default_flow_style=False) for d in docs)


FILES = {"networkpolicies.yaml": network_policies, "app-roles.yaml": app_roles}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--resolve-ports", action="store_true", help="re-render and rewrite the target-ports fixture")
    a = ap.parse_args()
    if a.resolve_ports:
        TARGET_PORTS_FILE.write_text("# GENERATED by scripts/life_sessions.py --resolve-ports: Service port -> pod ports\n"
                                     "# of every allowed in-cluster smoke target. Do not edit by hand.\n"
                                     + yaml.safe_dump({"targets": resolve_target_ports()}, sort_keys=True))
    stale = []
    for fname, fn in FILES.items():
        want = render(fn())
        path = MAN / fname
        if a.write:
            path.write_text(want)
        elif not path.exists() or path.read_text() != want:
            stale.append(fname)
    if stale:
        print("stale:", ", ".join(stale), "-- run scripts/life_sessions.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
