#!/usr/bin/env python3
"""Generate the upgrade-session network policies and per-app Roles (plan 2026-10-31--life--update-security-lifecycle, phase 5).

One table (ENDPOINTS) says what each upgrade type may reach; the policy facts
(scripts/tests/fixtures/life/app-facts.yaml) say which Frank apps are stateful or run Argo
Rollouts. From those two this writes:

  apps/upgrade-sessions/manifests/networkpolicies.yaml   default-deny + one egress policy per type
  apps/upgrade-sessions/manifests/app-roles.yaml         static Roles in each stateful / Rollouts
                                                          app namespace, bound to the session SAs

Usage: scripts/life_sessions.py [--write | --check]
"""
from __future__ import annotations

import argparse
import functools
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

import life_policy  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MAN = ROOT / "apps/upgrade-sessions/manifests"
NS = "upgrade-sessions"
TYPES = ("chart-major", "stateful", "rollouts", "frank-os", "hop-os")
TYPE_LABEL = "cluster-update.fr/type"
SEARCH = (f"{NS}.svc.cluster.local", "svc.cluster.local", "cluster.local")  # pod resolv.conf, ndots:5

GITHUB = ("api.github.com", "github.com")  # API commits + git fetch of frank; no gist/raw/uploads
MODELS = ("api.anthropic.com", "console.anthropic.com", "claude.ai", "platform.claude.com",
          "api.openai.com", "auth.openai.com", "chatgpt.com")
OMNI = "omni.frank.derio.net"
FRANK_NODES = ("192.168.55.21", "192.168.55.22", "192.168.55.23", "192.168.55.31",
               "192.168.55.71", "192.168.55.41", "192.168.55.42")
HEADSCALE = "headscale.hop.derio.net"
DERP = "derp*.tailscale.com"  # headscale's derp.urls is Tailscale's default map plus its own region

# Every type: GitHub, model providers, the kube API, the console's session API, Gitea (CI logs).
COMMON_FQDNS = [(GITHUB + MODELS, [("443", "TCP")])]
ENDPOINTS = {
    "chart-major": {"fqdns": COMMON_FQDNS},
    "stateful": {"fqdns": COMMON_FQDNS, "apps": "stateful"},
    "rollouts": {"fqdns": COMMON_FQDNS, "apps": "rollout"},
    "frank-os": {"fqdns": COMMON_FQDNS + [((OMNI,), [("443", "TCP")])],
                 "cidrs": (FRANK_NODES, [("50000", "TCP")])},
    "hop-os": {"fqdns": COMMON_FQDNS + [((HEADSCALE,), [("443", "TCP"), ("3478", "UDP")]),
                                        ((DERP,), [("443", "TCP"), ("3478", "UDP")])]},
}
HEADER = ("# GENERATED by scripts/life_sessions.py --write from its ENDPOINTS table and\n"
          "# scripts/tests/fixtures/life/app-facts.yaml. Do not edit by hand.\n")


@functools.lru_cache(maxsize=None)
def _destinations() -> dict[str, str]:
    return {a["key"]: a["app"]["spec"]["destination"].get("namespace", "default")
            for a in life_policy.applications()}


def app_namespaces(flag: str) -> list[str]:
    """Namespaces of the Frank apps whose fact `flag` (stateful | rollout) is true.

    Frank only: a session pod runs on Frank, and Hop's stateful apps sit on static Hetzner PVs
    with no Longhorn to snapshot. A Role here is inert on an app's own Services.
    """
    facts = life_policy.load_facts()
    dest = _destinations()
    return sorted({dest[k] for k, f in facts.items() if f[flag] and k.startswith("frank/") and k in dest})


# Namespaces a session never reaches over the network even when an app there is stateful:
# unauthenticated admin APIs (Longhorn manager :9500 can delete any volume; VictoriaMetrics and
# VictoriaLogs serve delete endpoints), the control plane, and the session machinery itself.
# gitea is not a target either: every type already reaches its HTTP port, and its SSH is not
# something a session needs.
UNREACHABLE = frozenset({"longhorn-system", "monitoring", "kube-system", "cluster-update-fr", NS, "gitea"})


def app_targets(flag: str) -> dict[str, list[int]]:
    """{namespace: Service ports} a session of this kind may reach for its smoke checks.

    The namespaces are those of the flagged apps; the ports are every Frank Service port in them
    (a Rollout's Services usually belong to a sibling app, e.g. litellm-extras -> litellm).
    """
    facts = life_policy.load_facts()
    wanted = set(app_namespaces(flag)) - UNREACHABLE
    out: dict[str, set[int]] = {}
    for k, f in facts.items():
        if not k.startswith("frank/"):
            continue
        for svc in f["services"]:
            if svc["namespace"] in wanted:
                out.setdefault(svc["namespace"], set()).update(p for p in svc["ports"] if p and p != 22)
    return {ns: sorted(p) for ns, p in sorted(out.items()) if p}


def _ports(pairs):
    return [{"ports": [{"port": p, "protocol": proto} for p, proto in pairs]}]


def _ep(**labels):
    return {"matchLabels": dict(labels)}


def _fqdn(name):
    return {"matchPattern": name} if "*" in name else {"matchName": name}


def _dns_names(typ: str) -> list[str]:
    spec = ENDPOINTS[typ]
    names = [n for group, _ in spec["fqdns"] for n in group]
    out = []
    for n in names:
        out += [n] + [f"{n}.{s}" for s in SEARCH]
    out += ["gitea-http.gitea.svc.cluster.local",
            "cluster-update-fr-session.cluster-update-fr.svc.cluster.local",
            "kubernetes.default.svc.cluster.local"]
    if "apps" in spec:
        out += [f"*.{ns}.svc.cluster.local" for ns in app_targets(spec["apps"])]
    return out


def type_policy(typ: str) -> dict:
    spec = ENDPOINTS[typ]
    egress = [{
        "toEndpoints": [_ep(**{"k8s:io.kubernetes.pod.namespace": "kube-system", "k8s-app": "kube-dns"})],
        "toPorts": [{"ports": [{"port": "53", "protocol": "UDP"}, {"port": "53", "protocol": "TCP"}],
                     "rules": {"dns": [_fqdn(n) for n in _dns_names(typ)]}}],
    }]
    for group, pairs in spec["fqdns"]:
        egress.append({"toFQDNs": [_fqdn(n) for n in group], "toPorts": _ports(pairs)})
    egress.append({"toEntities": ["kube-apiserver"], "toPorts": _ports([("6443", "TCP")])})
    egress.append({"toEndpoints": [_ep(**{"k8s:io.kubernetes.pod.namespace": "cluster-update-fr",
                                          "app.kubernetes.io/name": "cluster-update-fr"})],
                   "toPorts": _ports([("8081", "TCP")])})
    egress.append({"toEndpoints": [_ep(**{"k8s:io.kubernetes.pod.namespace": "gitea"})],
                   "toPorts": _ports([("3000", "TCP")])})
    if "cidrs" in spec:
        ips, pairs = spec["cidrs"]
        egress.append({"toCIDR": [f"{ip}/32" for ip in ips], "toPorts": _ports(pairs)})
    if "apps" in spec:
        # The target app's own Services, for the smoke checks R16 asks the session to run: one
        # rule per namespace, bound to the TCP ports its Services declare in the facts.
        for ns, nsports in app_targets(spec["apps"]).items():
            egress.append({"toEndpoints": [_ep(**{"k8s:io.kubernetes.pod.namespace": ns})],
                           "toPorts": _ports([(str(p), "TCP") for p in nsports])})
    return {"apiVersion": "cilium.io/v2", "kind": "CiliumNetworkPolicy",
            "metadata": {"name": f"upgrade-session-{typ}", "namespace": NS},
            "spec": {"endpointSelector": _ep(**{TYPE_LABEL: typ}), "egress": egress}}


def network_policies() -> list[dict]:
    deny = {"apiVersion": "cilium.io/v2", "kind": "CiliumNetworkPolicy",
            "metadata": {"name": "upgrade-sessions-default-deny", "namespace": NS},
            "spec": {"endpointSelector": {}, "ingress": [{}], "egress": [{}],
                     # A deny outranks every allow: no session reaches SSH anywhere (not the Omni
                     # host, not an in-cluster sshd such as secure-agent-pod's).
                     "egressDeny": [{"toEntities": ["all"], "toPorts": _ports([("22", "TCP")])}]}}
    return [deny] + [type_policy(t) for t in TYPES]


def _role(name, ns, rules):
    return {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "Role",
            "metadata": {"name": name, "namespace": ns}, "rules": rules}


def _binding(name, ns, sa):
    return {"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "RoleBinding",
            "metadata": {"name": name, "namespace": ns},
            "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "Role", "name": name},
            "subjects": [{"kind": "ServiceAccount", "name": sa, "namespace": NS}]}


def app_roles() -> list[dict]:
    out = []
    sa = "upgrade-session-stateful"
    name = "upgrade-session-stateful-snapshot"
    for ns in app_namespaces("stateful"):
        rules = [{"apiGroups": [""], "resources": ["persistentvolumeclaims"], "verbs": ["get", "list"]},
                 {"apiGroups": ["snapshot.storage.k8s.io"], "resources": ["volumesnapshots"],
                  "verbs": ["create", "get", "list"]}]
        if ns == "longhorn-system":
            rules.append({"apiGroups": ["longhorn.io"], "resources": ["snapshots"], "verbs": ["create", "get", "list"]})
        out += [_role(name, ns, rules), _binding(name, ns, sa)]
    if "longhorn-system" not in app_namespaces("stateful"):
        rules = [{"apiGroups": ["longhorn.io"], "resources": ["snapshots"], "verbs": ["create", "get", "list"]}]
        out += [_role(name, "longhorn-system", rules), _binding(name, "longhorn-system", sa)]
    sa = "upgrade-session-rollouts"
    name = "upgrade-session-rollouts-decide"
    for ns in app_namespaces("rollout"):
        rules = [{"apiGroups": ["argoproj.io"], "resources": ["rollouts"], "verbs": ["get", "list"]},
                 {"apiGroups": ["argoproj.io"], "resources": ["rollouts/status"], "verbs": ["patch"]}]
        out += [_role(name, ns, rules), _binding(name, ns, sa)]
    return out


def render(docs: list[dict]) -> str:
    return HEADER + "---\n".join(yaml.safe_dump(d, sort_keys=False, default_flow_style=False) for d in docs)


FILES = {"networkpolicies.yaml": network_policies, "app-roles.yaml": app_roles}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for fname, fn in FILES.items():
        want = render(fn())
        path = MAN / fname
        if a.write:
            path.write_text(want)
        elif not path.exists() or path.read_text() != want:
            stale.append(fname)
    if stale:
        print("stale:", ", ".join(stale), "-- run scripts/life_sessions.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
